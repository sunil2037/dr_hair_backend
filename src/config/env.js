import dotenv from 'dotenv';
import { randomBytes } from 'node:crypto';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Load environment variables from .env located at project root (if exists)
try {
  dotenv.config({ path: path.resolve(__dirname, '../../.env') });
} catch {
  // Ignore in serverless/production environments where .env is absent
}

const environment = (process.env.NODE_ENV || 'production').trim().toLowerCase();
const configuredJwtSecret = process.env.JWT_SECRET?.trim() || '';
const jwtSecret = configuredJwtSecret || (
  environment === 'development' || environment === 'test'
    ? randomBytes(32).toString('base64url')
    : ''
);
const configuredTestOtp = process.env.DEFAULT_TEST_OTP?.trim() || '';
if (configuredTestOtp && environment !== 'development' && environment !== 'test') {
  throw new Error('DEFAULT_TEST_OTP is only allowed in development. Remove it from this environment.');
}
const defaultTestOtp = environment === 'development'
  ? configuredTestOtp || '123456'
  : null;
const superAdminId = process.env.SUPER_ADMIN_ID?.trim().toLowerCase() || '';
const superAdminPasswordHash = process.env.SUPER_ADMIN_PASSWORD_HASH?.trim() || '';

if (!jwtSecret || jwtSecret.length < 32) {
  throw new Error('JWT_SECRET must be set to a unique value of at least 32 characters.');
}

if (configuredTestOtp && !/^\d{6}$/.test(configuredTestOtp)) {
  throw new Error('DEFAULT_TEST_OTP must contain exactly 6 digits when configured.');
}

if (environment === 'production' && (!superAdminId || !superAdminPasswordHash)) {
  throw new Error('SUPER_ADMIN_ID and SUPER_ADMIN_PASSWORD_HASH must be configured in production.');
}

if (environment === 'production' && !/^scrypt\$\d+\$\d+\$\d+\$[A-Za-z0-9_-]+\$[A-Za-z0-9_-]+$/.test(superAdminPasswordHash)) {
  throw new Error('SUPER_ADMIN_PASSWORD_HASH must be a valid hash generated by `npm run admin:setup`.');
}

if (environment === 'production' && !process.env.MONGODB_URI?.trim()) {
  throw new Error('MONGODB_URI must be configured in production.');
}

export const config = {
  env: environment,
  isDev: environment === 'development',
  port: parseInt(process.env.PORT, 10) || 5001,
  baseUrl: process.env.BASE_URL || `http://localhost:${process.env.PORT || 5001}`,
  
  jwt: {
    secret: jwtSecret,
    expiresIn: process.env.JWT_EXPIRES_IN || '30d',
  },

  mongodb: {
    uri: process.env.MONGODB_URI?.trim() || '',
  },

  admin: {
    superAdminId,
    superAdminPasswordHash,
    superAdminName: process.env.SUPER_ADMIN_NAME?.trim() || 'Dr. Hair Super Admin',
  },

  cors: {
    origins: (process.env.CORS_ORIGINS || '')
      .split(',')
      .map((origin) => origin.trim())
      .filter(Boolean),
  },
  
  upload: {
    maxFileSize: (parseInt(process.env.MAX_FILE_SIZE_MB, 10) || 10) * 1024 * 1024,
    maxMediaFileSize: (parseInt(process.env.MAX_MEDIA_FILE_SIZE_MB, 10) || 100) * 1024 * 1024,
    allowedMimeTypes: ['image/jpeg', 'image/png', 'image/webp', 'image/jpg'],
  },

  cloudinary: {
    cloudName: process.env.CLOUDINARY_CLOUD_NAME?.trim() || '',
    apiKey: process.env.CLOUDINARY_API_KEY?.trim() || '',
    apiSecret: process.env.CLOUDINARY_API_SECRET?.trim() || '',
    imageFolder: process.env.CLOUDINARY_IMAGE_FOLDER?.trim() || 'drhair/images',
    videoFolder: process.env.CLOUDINARY_VIDEO_FOLDER?.trim() || 'drhair/testing',
  },

  firebase: {
    projectId: process.env.FIREBASE_PROJECT_ID?.trim() || '',
    clientEmail: process.env.FIREBASE_CLIENT_EMAIL?.trim() || '',
    privateKey: process.env.FIREBASE_PRIVATE_KEY?.replace(/\\n/g, '\n').trim() || '',
  },
  
  otp: {
    defaultOtp: defaultTestOtp,
    expiryMinutes: parseInt(process.env.OTP_EXPIRY_MINUTES, 10) || 10,
  },
};

